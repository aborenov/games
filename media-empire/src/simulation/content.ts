function lead(
  day: number,
  slug: string,
  placeId: PlaceId,
  topic: Topic,
  title: string,
  summary: string,
  stakes: string,
  verifiedTitle: string,
  verifiedBody: string,
  effect?: Lead["effect"],
  critical = false,
): Lead {
  return {
    id: `${day}-${slug}`,
    placeId,
    topic,
    title,
    summary,
    stakes,
    briefTitle: title,
    verifiedTitle,
    briefBody: `${summary} Редакция передаёт доступные сведения; независимая проверка ещё не завершена.`,
    verifiedBody,
    ...(effect ? { effect } : {}),
    critical,
  };
}

